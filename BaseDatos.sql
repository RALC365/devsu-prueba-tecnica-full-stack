-- Base de datos: banco (PostgreSQL)

DROP TABLE IF EXISTS movimiento;
DROP TABLE IF EXISTS cuenta;
DROP TABLE IF EXISTS cliente;
DROP TABLE IF EXISTS persona;

CREATE TABLE persona (
    persona_id     BIGINT GENERATED BY DEFAULT AS IDENTITY,
    nombre         VARCHAR(100) NOT NULL,
    genero         VARCHAR(10)  NOT NULL,
    edad           INTEGER      NOT NULL,
    identificacion VARCHAR(20)  NOT NULL,
    direccion      VARCHAR(200) NOT NULL,
    telefono       VARCHAR(20)  NOT NULL,
    CONSTRAINT pk_persona PRIMARY KEY (persona_id),
    CONSTRAINT uk_persona_identificacion UNIQUE (identificacion),
    CONSTRAINT ck_persona_genero CHECK (genero IN ('MASCULINO', 'FEMENINO', 'OTRO')),
    CONSTRAINT ck_persona_edad CHECK (edad BETWEEN 1 AND 120)
);

-- cliente_id es la misma PK de persona (herencia)
CREATE TABLE cliente (
    cliente_id BIGINT       NOT NULL,
    contrasena VARCHAR(100) NOT NULL,
    estado     BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_cliente PRIMARY KEY (cliente_id),
    CONSTRAINT fk_cliente_persona FOREIGN KEY (cliente_id) REFERENCES persona (persona_id)
);

CREATE TABLE cuenta (
    cuenta_id        BIGINT GENERATED BY DEFAULT AS IDENTITY,
    numero_cuenta    VARCHAR(20)    NOT NULL,
    tipo_cuenta      VARCHAR(10)    NOT NULL,
    saldo_inicial    NUMERIC(15, 2) NOT NULL,
    saldo_disponible NUMERIC(15, 2) NOT NULL,
    estado           BOOLEAN        NOT NULL DEFAULT TRUE,
    cliente_id       BIGINT         NOT NULL,
    CONSTRAINT pk_cuenta PRIMARY KEY (cuenta_id),
    CONSTRAINT uk_cuenta_numero_cuenta UNIQUE (numero_cuenta),
    CONSTRAINT fk_cuenta_cliente FOREIGN KEY (cliente_id) REFERENCES cliente (cliente_id),
    CONSTRAINT ck_cuenta_tipo CHECK (tipo_cuenta IN ('AHORROS', 'CORRIENTE')),
    CONSTRAINT ck_cuenta_saldo_inicial CHECK (saldo_inicial >= 0),
    CONSTRAINT ck_cuenta_saldo_disponible CHECK (saldo_disponible >= 0)
);

CREATE INDEX ix_cuenta_cliente ON cuenta (cliente_id);

-- valor: positivo en créditos, negativo en débitos
CREATE TABLE movimiento (
    movimiento_id   BIGINT GENERATED BY DEFAULT AS IDENTITY,
    fecha           TIMESTAMP      NOT NULL,
    tipo_movimiento VARCHAR(10)    NOT NULL,
    valor           NUMERIC(15, 2) NOT NULL,
    saldo           NUMERIC(15, 2) NOT NULL,
    cuenta_id       BIGINT         NOT NULL,
    CONSTRAINT pk_movimiento PRIMARY KEY (movimiento_id),
    CONSTRAINT fk_movimiento_cuenta FOREIGN KEY (cuenta_id) REFERENCES cuenta (cuenta_id),
    CONSTRAINT ck_movimiento_tipo CHECK (tipo_movimiento IN ('CREDITO', 'DEBITO')),
    CONSTRAINT ck_movimiento_signo CHECK (
        (tipo_movimiento = 'CREDITO' AND valor > 0) OR (tipo_movimiento = 'DEBITO' AND valor < 0)),
    CONSTRAINT ck_movimiento_saldo CHECK (saldo >= 0)
);

CREATE INDEX ix_movimiento_cuenta_fecha ON movimiento (cuenta_id, fecha);
